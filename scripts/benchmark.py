"""Benchmark: naive person-day GLM vs the aggregated sufficient-statistics GLM.

    python scripts/benchmark.py   # writes docs/figures/benchmark.png and docs/benchmark.md

Both pipelines produce identical estimates (see tests); this measures cost only.
"""

from __future__ import annotations

import time
import tracemalloc
import warnings
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib.ticker import FuncFormatter  # noqa: E402

from vvi import aggregate, fit, person_days, simulate  # noqa: E402
from vvi.plots import INK, INK_2, PLATFORM_COLORS, SURFACE, style  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
NAIVE_SIZES = [1_000, 2_500, 5_000]
AGG_SIZES = [1_000, 2_500, 5_000, 30_000, 300_000, 1_000_000]


def run_aggregated(cohort):
    table = aggregate(cohort.people, cohort.events, horizon=cohort.horizon)
    return table, fit(table, reference="BB")


def run_person_day(cohort):
    table = person_days(cohort.people, cohort.events)
    return table, fit(table, reference="BB")


def timed(fn, *args):
    tracemalloc.start()
    t = time.perf_counter()
    out = fn(*args)
    dt = time.perf_counter() - t
    peak = tracemalloc.get_traced_memory()[1] / 2**20
    tracemalloc.stop()
    return out, dt, peak


def main() -> None:
    rows = []
    for n in sorted(set(NAIVE_SIZES) | set(AGG_SIZES)):
        c = simulate(n, seed=n)
        warnings.simplefilter("ignore", RuntimeWarning)  # tiny cohorts: empty profiles
        if n in AGG_SIZES:
            (tab, _), dt, mem = timed(run_aggregated, c)
            rows.append(("aggregated", n, len(tab), int(tab["at_risk"].sum()), dt, mem))
        if n in NAIVE_SIZES:
            (tab, _), dt, mem = timed(run_person_day, c)
            rows.append(("person-day", n, len(tab), len(tab), dt, mem))
        print(rows[-1])

    md = [
        "| pipeline | people | GLM rows | person-days | build + fit (s) | peak memory (MiB) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        md.append(f"| {r[0]} | {r[1]:,} | {r[2]:,} | {r[3]:,} | {r[4]:.2f} | {r[5]:,.0f} |")
    (ROOT / "docs" / "benchmark.md").write_text(
        "# Benchmark\n\nGenerated by `scripts/benchmark.py` on a synthetic cohort "
        "(single CPU process). Identical estimates; only the cost differs.\n\n"
        + "\n".join(md)
        + "\n"
    )

    fig, axes = plt.subplots(1, 2, figsize=(8.6, 3.5), facecolor=SURFACE)
    for ax, col, label in ((axes[0], 4, "Build + fit time (s)"), (axes[1], 5, "Peak memory (MiB)")):
        style(ax)
        ax.grid(axis="y", color="#e6e5e1", lw=0.8)
        for name, color in (
            ("person-day", PLATFORM_COLORS["S"]),
            ("aggregated", PLATFORM_COLORS["B"]),
        ):
            pts = [(r[1], r[col]) for r in rows if r[0] == name]
            x, y = np.array(pts).T
            ax.plot(x, y, "-o", color=color, lw=2, ms=6, mec=SURFACE, mew=1.5)
            ax.annotate(
                name,
                (x[-1], y[-1]),
                xytext=(6, 0),
                textcoords="offset points",
                va="center",
                fontsize=9,
                color=INK_2,
            )
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:,.0f}"))
        ax.yaxis.set_major_formatter(
            FuncFormatter(lambda v, _: f"{v:,.0f}" if v >= 1 else f"{v:g}")
        )
        ax.set_xlabel("Cohort size (people)", color=INK_2, fontsize=9)
        ax.set_title(label, loc="left", color=INK, fontsize=10.5, fontweight="bold")
    fig.suptitle(
        "Same likelihood, a table that does not grow with the cohort",
        x=0.01,
        ha="left",
        color=INK,
        fontsize=12,
        fontweight="bold",
    )
    fig.tight_layout()
    fig.savefig(ROOT / "docs" / "figures" / "benchmark.png", dpi=200)
    print((ROOT / "docs" / "benchmark.md").read_text())


if __name__ == "__main__":
    main()
