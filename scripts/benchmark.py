"""Benchmark: naive person-day GLM vs the aggregated sufficient-statistics GLM.

    python scripts/benchmark.py   # writes docs/results/benchmark.json and docs/benchmark.md
    python scripts/make_figures.py   # then redraws docs/figures/benchmark.png

Both pipelines produce identical estimates (see tests); this measures cost only.
"""

from __future__ import annotations

import json
import time
import tracemalloc
import warnings
from pathlib import Path

from vvi import aggregate, fit, person_days, simulate

ROOT = Path(__file__).resolve().parents[1]
NAIVE_SIZES = [1_000, 2_500, 5_000]
AGG_SIZES = [1_000, 2_500, 5_000, 30_000, 300_000, 1_000_000]


def run_aggregated(cohort):
    table = aggregate(cohort.people, cohort.events, horizon=cohort.horizon)
    return table, fit(table, reference="BB")


def run_person_day(cohort):
    table = person_days(cohort.people, cohort.events)
    return table, fit(table, reference="BB")


def timed(fn, *args):
    tracemalloc.start()
    t = time.perf_counter()
    out = fn(*args)
    dt = time.perf_counter() - t
    peak = tracemalloc.get_traced_memory()[1] / 2**20
    tracemalloc.stop()
    return out, dt, peak


def main() -> None:
    rows = []
    for n in sorted(set(NAIVE_SIZES) | set(AGG_SIZES)):
        c = simulate(n, seed=n)
        warnings.simplefilter("ignore", RuntimeWarning)  # tiny cohorts: empty profiles
        if n in AGG_SIZES:
            (tab, _), dt, mem = timed(run_aggregated, c)
            rows.append(("aggregated", n, len(tab), int(tab["at_risk"].sum()), dt, mem))
        if n in NAIVE_SIZES:
            (tab, _), dt, mem = timed(run_person_day, c)
            rows.append(("person-day", n, len(tab), len(tab), dt, mem))
        print(rows[-1])

    md = [
        "| pipeline | people | GLM rows | person-days | build + fit (s) | peak memory (MiB) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        md.append(f"| {r[0]} | {r[1]:,} | {r[2]:,} | {r[3]:,} | {r[4]:.2f} | {r[5]:,.0f} |")
    (ROOT / "docs" / "benchmark.md").write_text(
        "# Benchmark\n\nGenerated by `scripts/benchmark.py` on a synthetic cohort "
        "(single CPU process). Identical estimates; only the cost differs.\n\n"
        + "\n".join(md)
        + "\n"
    )

    (ROOT / "docs" / "results").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "results" / "benchmark.json").write_text(
        json.dumps(
            {
                "rows": [
                    dict(
                        pipeline=r[0],
                        people=r[1],
                        glm_rows=r[2],
                        person_days=r[3],
                        seconds=round(r[4], 2),
                        mib=round(r[5], 1),
                    )
                    for r in rows
                ],
                "machine": "2 vCPU, 7 GB RAM, single process",
            },
            indent=1,
        )
    )
    print((ROOT / "docs" / "benchmark.md").read_text())


if __name__ == "__main__":
    main()
