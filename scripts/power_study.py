"""Power of the imprinting contrast (BBBI vs BBI) against cohort size.

    python scripts/power_study.py      # writes docs/synthetic/power.json and docs/power.md

Analytic curves come from one large fit per effect size (``vvi.power``, SE ∝ 1/√n);
Monte-Carlo replicates at three sizes check them, and a null scenario checks the
test's size. Everything is simulated — no real data.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

import numpy as np

import vvi
from vvi import Truth, aggregate, fit, simulate

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "synthetic"
HRS = (1.10, 1.20, 1.30)
SIZES = np.geomspace(30_000, 3_000_000, 60)
N_FIT = 1_000_000
MC_HR = 1.20
MC_SIZES = (100_000, 300_000, 1_000_000)
REPS = 30


def truth_for(hr: float) -> Truth:
    t = Truth()
    t.profile_effects = dict(t.profile_effects)
    t.profile_effects["BBBI"] = t.profile_effects["BBI"] + float(np.log(hr))
    return t


def contrast_at(n: int, hr: float, seed: int) -> vvi.Effect:
    c = simulate(n, seed=seed, truth=truth_for(hr))
    f = fit(aggregate(c.people, c.events, horizon=c.horizon), reference="BB")
    return f.contrast("BBBI", "BBI")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    t0 = time.perf_counter()
    curves = {}
    for k, hr in enumerate(HRS):
        e = contrast_at(N_FIT, hr, seed=100 + k)
        curves[f"HR {hr:.2f}"] = {
            "power": vvi.power(e, N_FIT, SIZES, log_hr=np.log(hr)).tolist(),
            "se_at_1M": e.se,
            "n80": vvi.required_size(e, N_FIT, log_hr=np.log(hr)),
        }
        print(f"HR {hr}: se {e.se:.4f}, n80 {curves[f'HR {hr:.2f}']['n80']:,}")

    mc = {"sizes": list(MC_SIZES), "power": [], "half_width": []}
    for n in MC_SIZES:
        hits = [contrast_at(n, MC_HR, seed=10_000 + n // 1000 + r).ci[0] > 1 for r in range(REPS)]
        p = float(np.mean(hits))
        mc["power"].append(p)
        mc["half_width"].append(float(1.96 * np.sqrt(max(p * (1 - p), 1e-9) / REPS)))
        print(f"MC n={n:,}: power {p:.2f}")

    null = [contrast_at(300_000, 1.0, seed=50_000 + r) for r in range(REPS)]
    size = float(np.mean([e.p < 0.05 for e in null]))
    print(f"null rejection rate at 300k: {size:.3f}")

    result = {
        "sizes": SIZES.tolist(),
        "curves": curves,
        "monte_carlo": {f"HR {MC_HR:.2f}": mc},
        "null_rejection_300k": size,
        "reps": REPS,
        "n_fit": N_FIT,
        "seconds": round(time.perf_counter() - t0, 1),
    }
    (OUT / "power.json").write_text(json.dumps(result, indent=1))
    lines = [
        "# Power of the imprinting contrast",
        "",
        "Generated by `scripts/power_study.py` (synthetic cohorts only). Contrast: "
        "`BBBI vs BBI`; two-sided Wald test at α = 0.05.",
        "",
        "| true HR | SE at 1M people | people for 80% power |",
        "|---|---:|---:|",
    ]
    for label, c in curves.items():
        lines.append(f"| {label[3:]} | {c['se_at_1M']:.4f} | {c['n80']:,} |")
    lines += [
        "",
        f"Monte-Carlo check (HR {MC_HR:.2f}, {REPS} replicates per size, "
        "proportion of 95% CIs entirely above 1):",
        "",
        "| people | simulated power | analytic power |",
        "|---:|---:|---:|",
    ]
    ana = np.interp(MC_SIZES, SIZES, curves[f"HR {MC_HR:.2f}"]["power"])
    for n, p, a in zip(MC_SIZES, mc["power"], ana, strict=True):
        lines.append(f"| {n:,} | {p:.2f} | {a:.2f} |")
    lines += [
        "",
        f"Null scenario (HR 1.00, 300k people): rejection rate {size:.2f} "
        f"over {REPS} replicates (nominal 0.05).",
        "",
    ]
    (ROOT / "docs" / "power.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
